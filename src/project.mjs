// Compiles the scenes of a Babylon.js Editor project into <outDir>/scene.generated.ts.
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { PROVIDED, SceneCompileError, compileModule } from './compile.mjs';

export const DEFAULT_OUT_DIR = '.babylon-compiled';

/**
 * @param {{ root: string; scenes?: string[]; outDir?: string; sceneDir?: string; lazyTextures?: boolean; images?: Record<string, string> }} options
 *   root: the editor project (where project.bjseditor is);
 *   scenes: exported scene file names to compile (default: every .babylon in sceneDir);
 *   sceneDir: where the editor exports (default public/scene);
 *   lazyTextures: textures load when first drawn instead of with the scene;
 *   images: texture path → re-encoded path (from images.mjs encodeImages).
 * @returns {{ module: string; empty: string; scenes: string[] }}
 */
export function compileProject(options) {
  const root = options.root;
  const outDir = join(root, options.outDir ?? DEFAULT_OUT_DIR);
  const { sceneDir, files, scenes } = readScenes(options);

  checkEditorToolsImports(join(root, 'src'));

  const sources = files.map((file) => relative(root, join(sceneDir, file)).split('\\').join('/')).join(', ');
  const code = compileModule(scenes, `// GENERATED by babylon-scene-compiler from ${sources}.`, { lazyTextures: options.lazyTextures, images: options.images });
  mkdirSync(outDir, { recursive: true });
  const module = join(outDir, 'scene.generated.ts');
  const empty = join(outDir, 'empty.ts');
  writeFileSync(module, code);
  writeFileSync(empty, '// Stand-in for editor runtime modules left out of the compiled build.\nexport {};\n');
  writeFileSync(join(outDir, '.gitignore'), '*\n');
  return { module, empty, scenes: files };
}

/**
 * The exported scenes of a project, parsed.
 * @param {{ root: string; scenes?: string[]; sceneDir?: string }} options
 */
export function readScenes(options) {
  const sceneDir = join(options.root, options.sceneDir ?? 'public/scene');
  if (!existsSync(sceneDir)) throw new SceneCompileError(`[babylon-scene-compiler] no exported scenes in ${sceneDir}: export the project from the Babylon.js Editor first`);
  const files = options.scenes ?? readdirSync(sceneDir).filter((file) => file.endsWith('.babylon'));
  if (!files.length) throw new SceneCompileError(`[babylon-scene-compiler] no .babylon file in ${sceneDir}`);
  const scenes = files.map((file) => ({ file, data: JSON.parse(readFileSync(join(sceneDir, file), 'utf8')) }));
  return { sceneDir, files, scenes };
}

/** Fails if project code imports from babylonjs-editor-tools something the compiled module lacks. */
function checkEditorToolsImports(dir) {
  if (!existsSync(dir)) return;
  const missing = [];
  const visit = (path) => {
    for (const name of readdirSync(path)) {
      const full = join(path, name);
      if (statSync(full).isDirectory()) {
        if (name !== 'node_modules') visit(full);
        continue;
      }
      if (!/\.(m?[jt]sx?)$/.test(name)) continue;
      const source = readFileSync(full, 'utf8');
      for (const match of source.matchAll(/import\s+(type\s+)?\{([^}]*)\}\s+from\s+["']babylonjs-editor-tools["']/g)) {
        if (match[1]) continue;
        for (const item of match[2].split(',')) {
          const imported = item.trim().replace(/^type\s+/, '').split(/\s+as\s+/)[0];
          if (imported && !item.trim().startsWith('type ') && !PROVIDED.has(imported)) missing.push(`${relative(dir, full)}: ${imported}`);
        }
      }
    }
  };
  visit(dir);
  if (missing.length) {
    throw new SceneCompileError(`[babylon-scene-compiler] these imports from babylonjs-editor-tools have no compiled equivalent:\n  ${missing.join('\n  ')}`);
  }
}
